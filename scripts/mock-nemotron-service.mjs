#!/usr/bin/env node

/**
 * Mock Nemotron Service for Development Testing
 * 
 * This simulates the standalone Nemotron service for testing the Mossy app's
 * integration without needing the full Python service binary.
 * 
 * Usage: node scripts/mock-nemotron-service.mjs
 * 
 * The app will auto-detect and connect to this service.
 */

import http from 'http';
import { fileURLToPath } from 'url';
import path from 'path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PORT = 5000;

// Mock response templates
const mockResponses = {
    health: {
        status: 'healthy',
        uptime: 123.45,
        model: 'nemotron-3-super',
        version: '1.0.0-mock'
    },
    generate: {
        text: 'This is a mock response from the Nemotron service. In production, this would be generated by the actual NVIDIA Nemotron model.',
        tokens: 25,
        generation_time_ms: 450
    },
    config: {
        model: 'nemotron-3-super',
        max_tokens: 2048,
        temperature: 0.7,
        enabled: true
    }
};

// Request counters for logging
let requestCount = 0;

const server = http.createServer((req, res) => {
    const url = new URL(req.url, `http://${req.headers.host}`);
    const pathname = url.pathname;

    requestCount++;

    // CORS headers
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
    res.setHeader('Content-Type', 'application/json');

    // Handle preflight
    if (req.method === 'OPTIONS') {
        res.writeHead(200);
        res.end();
        return;
    }

    console.log(`[${new Date().toLocaleTimeString()}] ${req.method} ${pathname}`);

    // Routes
    if (pathname === '/health' && req.method === 'GET') {
        res.writeHead(200);
        res.end(JSON.stringify(mockResponses.health));
        console.log('  ✓ Health check responded');
    }
    else if (pathname === '/generate' && req.method === 'POST') {
        let body = '';
        req.on('data', chunk => body += chunk);
        req.on('end', () => {
            try {
                const payload = JSON.parse(body);
                console.log(`  ✓ Generation request received:`, payload.prompt?.substring(0, 50) + '...');

                const response = {
                    ...mockResponses.generate,
                    prompt: payload.prompt || '',
                    request_id: `mock-${requestCount}`,
                    timestamp: new Date().toISOString()
                };

                res.writeHead(200);
                res.end(JSON.stringify(response));
            } catch (error) {
                res.writeHead(400);
                res.end(JSON.stringify({ error: 'Invalid JSON' }));
            }
        });
    }
    else if (pathname === '/config' && req.method === 'GET') {
        res.writeHead(200);
        res.end(JSON.stringify(mockResponses.config));
        console.log('  ✓ Config responded');
    }
    else if (pathname === '/' && req.method === 'GET') {
        res.writeHead(200);
        res.end(JSON.stringify({
            name: 'Nemotron Mock Service',
            version: '1.0.0-mock',
            status: 'running',
            timestamp: new Date().toISOString()
        }));
        console.log('  ✓ Root endpoint responded');
    }
    else {
        res.writeHead(404);
        res.end(JSON.stringify({ error: 'Not found' }));
        console.log('  ✗ Route not found');
    }
});

server.on('error', (error) => {
    if (error.code === 'EADDRINUSE') {
        console.error(`\n❌ ERROR: Port ${PORT} is already in use!`);
        console.error('Please stop the other process using this port and try again.');
        console.error('\nTo find the process:');
        console.error(`  netstat -ano | findstr :${PORT}`);
        console.error('\nTo kill it:');
        console.error('  taskkill /PID [PID] /F');
    } else {
        console.error('Server error:', error);
    }
    process.exit(1);
});

server.listen(PORT, 'localhost', () => {
    console.log('\n' + '='.repeat(70));
    console.log('🚀 Mock Nemotron Service Started');
    console.log('='.repeat(70));
    console.log(`\n📡 Listening on: http://localhost:${PORT}`);
    console.log(`\n💡 In another terminal, run: npm run dev`);
    console.log('\n📊 Endpoints:');
    console.log(`   GET  /health   - Health check`);
    console.log(`   POST /generate - Generate text`);
    console.log(`   GET  /config   - Get configuration`);
    console.log(`   GET  /         - Service info`);
    console.log('\n📝 What to test:');
    console.log(`   1. Start this service`);
    console.log(`   2. Run: npm run dev`);
    console.log(`   3. App should auto-detect and connect`);
    console.log(`   4. Check DevTools console for connection status`);
    console.log(`   5. Try using Nemotron features in the app`);
    console.log('\n⏹️  Press Ctrl+C to stop this service\n');
    console.log('='.repeat(70));
    console.log('\n📋 Request Log:\n');
});

// Graceful shutdown
process.on('SIGINT', () => {
    console.log('\n\n[SIGINT] Shutting down gracefully...');
    server.close(() => {
        console.log('✅ Server closed');
        process.exit(0);
    });

    // Force exit after 5 seconds
    setTimeout(() => {
        console.log('⚠️  Force closing after timeout');
        process.exit(1);
    }, 5000);
});

process.on('SIGTERM', () => {
    console.log('\n[SIGTERM] Server shutting down');
    process.exit(0);
});
