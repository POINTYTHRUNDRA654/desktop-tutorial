import type { Mo2PluginEntry } from './types';

/** @deprecated Use generatePRPCombinedPatchScript for a real, functional script. */
export const generateXEditScriptStub = (plugins: Mo2PluginEntry[]) =>
  generatePRPCombinedPatchScript(plugins);

/**
 * Generates a real, functional FO4Edit/xEdit Pascal script that:
 *  1. Creates "Mossy Combined Patch.esp" (or opens it if already loaded)
 *  2. Adds every enabled plugin as a master
 *  3. Copies the winning override of every conflicted record into the patch
 *  4. For CELL records: clears XCRI / XCMO so PRP manages precombines cleanly
 *
 * Run in FO4Edit: right-click any plugin -> Apply Script -> select this file.
 * FO4Edit must already have your full load order loaded.
 */
export const generatePRPCombinedPatchScript = (plugins: Mo2PluginEntry[]): string => {
  const enabled = plugins.filter(p => p.enabled).map(p => p.name);
  const masterLines = enabled
    .map(p => `  AddMasterIfMissing(patch, '${p.replace(/'/g, "''")}');`)
    .join('\n');
  const pluginList = enabled
    .map(p => `  //   ${p}`)
    .join('\n');

  return [
    'unit UserScript;',
    '{',
    '  Mossy - PRP-Compatible Combined Patch Script',
    '  Generated by Mossy (https://mossy.space)',
    '',
    '  What this script does:',
    '    1. Creates "Mossy Combined Patch.esp" (or opens it if already present).',
    '    2. Adds every enabled plugin in your load order as a master.',
    '    3. Iterates over ALL records across all loaded plugins.',
    '       - Records with conflicts: the winning override is copied into the patch.',
    '       - CELL records: XCRI/XCMO (precombine refs) are cleared for PRP compatibility.',
    '    4. Reports results in the xEdit Messages panel.',
    '',
    '  Load order detected when this script was generated:',
    (pluginList || '  //   (none - pick your MO2 profile first)'),
    '',
    '  Requirements:',
    '    - FO4Edit / xEdit 4.x+ loaded with your FULL load order',
    '    - Wait for background loading before running',
    '',
    '  How to run:',
    '    1. Open FO4Edit and load your entire load order.',
    '    2. Wait for background loading to finish.',
    '    3. Right-click any plugin -> "Apply Script".',
    '    4. Browse to this .pas file and click OK.',
    '    5. Wait for completion (may take several minutes for large load orders).',
    '    6. Save and exit FO4Edit.',
    '    7. Enable "Mossy Combined Patch.esp" at the BOTTOM of your MO2 load order.',
    '    8. If using PRP, load PRP BEFORE this patch.',
    '}',
    '',
    'var',
    '  patch: IInterface;',
    '  patchFileName: string;',
    '  recordsCopied: integer;',
    '  cellsFixed: integer;',
    '',
    'function Initialize: integer;',
    'var',
    '  i: integer;',
    'begin',
    '  Result := 0;',
    "  patchFileName := 'Mossy Combined Patch.esp';",
    '  recordsCopied := 0;',
    '  cellsFixed := 0;',
    '',
    "  AddMessage('[Mossy] Starting PRP-compatible combined patch generation...');",
    '',
    '  // Reuse an already-loaded patch file if present.',
    '  for i := 0 to Pred(FileCount) do begin',
    '    if GetFileName(FileByIndex(i)) = patchFileName then begin',
    '      patch := FileByIndex(i);',
    "      AddMessage('[Mossy] Found existing patch file: ' + patchFileName);",
    '      Break;',
    '    end;',
    '  end;',
    '',
    '  if not Assigned(patch) then begin',
    '    patch := AddNewFile;',
    '    if not Assigned(patch) then begin',
    "      AddMessage('[Mossy] ERROR: Could not create patch file. Aborting.');",
    '      Result := 1;',
    '      Exit;',
    '    end;',
    '    SetFileName(patch, patchFileName);',
    "    AddMessage('[Mossy] Created new patch file: ' + patchFileName);",
    '  end;',
    '',
    '  // Add all enabled plugins as masters.',
    masterLines || '  // (no plugins detected)',
    '',
    "  AddMessage('[Mossy] Masters added. Processing records...');",
    'end;',
    '',
    '// Called for every record in every loaded plugin.',
    'function Process(e: IInterface): integer;',
    'var',
    '  winning: IInterface;',
    '  copied: IInterface;',
    '  sig: string;',
    '  xcri, xcmo: IInterface;',
    'begin',
    '  Result := 0;',
    '',
    '  // Skip non-record elements.',
    '  if ElementType(e) <> etMainRecord then Exit;',
    '',
    '  // Skip records already in our patch.',
    '  if GetFile(e) = patch then Exit;',
    '',
    '  // Only process records that conflict with at least one other plugin.',
    '  if ConflictThisForMainRecord(e) < ctOverride then Exit;',
    '',
    '  // Get the winning (last-loading) override.',
    '  winning := WinningOverride(e);',
    '  if not Assigned(winning) then Exit;',
    '  if GetFile(winning) = patch then Exit;',
    '',
    '  // Copy winning override into the patch.',
    '  copied := wbCopyElementToFile(winning, patch, False, True);',
    '  if not Assigned(copied) then Exit;',
    '',
    '  Inc(recordsCopied);',
    '  sig := Signature(copied);',
    '',
    '  // PRP compatibility: clear precombine refs from CELL records.',
    "  if sig = 'CELL' then begin",
    "    xcri := ElementBySignature(copied, 'XCRI');",
    '    if Assigned(xcri) then begin',
    '      Remove(xcri);',
    '      Inc(cellsFixed);',
    '    end;',
    "    xcmo := ElementBySignature(copied, 'XCMO');",
    '    if Assigned(xcmo) then Remove(xcmo);',
    '  end;',
    '',
    '  Result := 0;',
    'end;',
    '',
    'function Finalize: integer;',
    'begin',
    "  AddMessage('');",
    "  AddMessage('[Mossy] ========================================');",
    "  AddMessage('[Mossy] Combined patch generation complete!');",
    "  AddMessage('[Mossy]   Records copied      : ' + IntToStr(recordsCopied));",
    "  AddMessage('[Mossy]   CELL records for PRP: ' + IntToStr(cellsFixed));",
    "  AddMessage('[Mossy]   Patch file          : ' + patchFileName);",
    "  AddMessage('[Mossy] ========================================');",
    "  AddMessage('[Mossy] Next steps:');",
    "  AddMessage('[Mossy]   1. Save and exit FO4Edit.');",
    "  AddMessage('[Mossy]   2. Enable \"' + patchFileName + '\" in MO2.');",
    "  AddMessage('[Mossy]   3. Place it at the VERY BOTTOM of your load order.');",
    "  AddMessage('[Mossy]   4. If using PRP, load PRP BEFORE this patch.');",
    "  AddMessage('');",
    '  Result := 0;',
    'end;',
    '',
    'end.',
  ].join('\n');
};

/**
 * Generates a real FO4Edit/xEdit Pascal script for a single mod that:
 *  1. Creates "YourMod_PRPPatch.esp" as a companion patch
 *  2. Adds the source mod as a master
 *  3. Copies every CELL record touched by the mod into the patch
 *  4. Clears XCRI / XCMO from each CELL so PRP can manage precombines
 *
 * Use this AFTER rebuilding precombines for your mod in the Creation Kit.
 * The resulting companion ESP makes your mod fully PRP-compatible.
 */
export const generateSingleModPRPPatchScript = (modFileName: string): string => {
  const safeMod = modFileName.replace(/'/g, "''");
  const patchName = modFileName.replace(/\.(esp|esm|esl)$/i, '') + '_PRPPatch.esp';
  const safePatch = patchName.replace(/'/g, "''");

  return [
    'unit UserScript;',
    '{',
    `  Mossy - Single-Mod PRP Compatibility Patch: ${modFileName}`,
    '  Generated by Mossy (https://mossy.space)',
    '',
    '  What this script does:',
    `    1. Creates "${patchName}" as a companion PRP patch.`,
    `    2. Adds "${modFileName}" as the only master.`,
    '    3. Copies every CELL record that your mod touches.',
    '    4. Clears XCRI / XCMO from each copied CELL so PRP manages precombines.',
    '',
    '  When to run this script:',
    '    - AFTER you have rebuilt precombines for your mod in the Creation Kit.',
    '    - Load ONLY your mod and its masters in FO4Edit (not your full load order).',
    '',
    '  How to run:',
    '    1. Open FO4Edit with ONLY your mod and its required masters loaded.',
    `    2. Wait for "${modFileName}" to fully load.`,
    '    3. Right-click any plugin -> "Apply Script".',
    '    4. Browse to this .pas file and click OK.',
    '    5. Save and exit.',
    `    6. Enable "${patchName}" in MO2 AFTER your mod.`,
    '    7. Load PRP BEFORE both your mod and this patch.',
    '}',
    '',
    'var',
    '  sourceMod: IInterface;',
    '  patch: IInterface;',
    '  patchFileName: string;',
    '  sourceName: string;',
    '  cellsCopied: integer;',
    '  cellsFixed: integer;',
    '',
    'function Initialize: integer;',
    'var',
    '  i: integer;',
    'begin',
    '  Result := 0;',
    `  sourceName := '${safeMod}';`,
    `  patchFileName := '${safePatch}';`,
    '  cellsCopied := 0;',
    '  cellsFixed := 0;',
    '',
    "  AddMessage('[Mossy] Single-Mod PRP Patch - looking for: ' + sourceName);",
    '',
    '  // Find the source mod in the loaded files.',
    '  for i := 0 to Pred(FileCount) do begin',
    '    if GetFileName(FileByIndex(i)) = sourceName then begin',
    '      sourceMod := FileByIndex(i);',
    "      AddMessage('[Mossy] Found source mod: ' + sourceName);",
    '      Break;',
    '    end;',
    '  end;',
    '',
    '  if not Assigned(sourceMod) then begin',
    "    AddMessage('[Mossy] ERROR: ' + sourceName + ' is not loaded. Load it in FO4Edit first.');",
    '    Result := 1;',
    '    Exit;',
    '  end;',
    '',
    '  // Create (or reuse) the patch file.',
    '  for i := 0 to Pred(FileCount) do begin',
    '    if GetFileName(FileByIndex(i)) = patchFileName then begin',
    '      patch := FileByIndex(i);',
    "      AddMessage('[Mossy] Found existing patch file: ' + patchFileName);",
    '      Break;',
    '    end;',
    '  end;',
    '',
    '  if not Assigned(patch) then begin',
    '    patch := AddNewFile;',
    '    if not Assigned(patch) then begin',
    "      AddMessage('[Mossy] ERROR: Could not create patch file.');",
    '      Result := 1;',
    '      Exit;',
    '    end;',
    '    SetFileName(patch, patchFileName);',
    "    AddMessage('[Mossy] Created patch file: ' + patchFileName);",
    '  end;',
    '',
    '  // The only master we need is the source mod.',
    '  AddMasterIfMissing(patch, sourceName);',
    "  AddMessage('[Mossy] Processing CELL records from ' + sourceName + '...');",
    'end;',
    '',
    '// Called for every record in every loaded plugin.',
    'function Process(e: IInterface): integer;',
    'var',
    '  copied: IInterface;',
    '  xcri, xcmo: IInterface;',
    'begin',
    '  Result := 0;',
    '',
    '  // Only handle main records.',
    '  if ElementType(e) <> etMainRecord then Exit;',
    '',
    '  // Only process records that belong to our source mod.',
    '  if GetFile(e) <> sourceMod then Exit;',
    '',
    '  // Only handle CELL records (exterior and interior cells).',
    "  if Signature(e) <> 'CELL' then Exit;",
    '',
    '  // Copy the CELL record into our patch.',
    '  copied := wbCopyElementToFile(e, patch, False, True);',
    '  if not Assigned(copied) then Exit;',
    '',
    '  Inc(cellsCopied);',
    '',
    '  // Clear precombine references for PRP compatibility.',
    "  xcri := ElementBySignature(copied, 'XCRI');",
    '  if Assigned(xcri) then begin',
    '    Remove(xcri);',
    '    Inc(cellsFixed);',
    '  end;',
    "  xcmo := ElementBySignature(copied, 'XCMO');",
    '  if Assigned(xcmo) then Remove(xcmo);',
    '',
    '  Result := 0;',
    'end;',
    '',
    'function Finalize: integer;',
    'begin',
    "  AddMessage('');",
    "  AddMessage('[Mossy] ======================================');",
    "  AddMessage('[Mossy] Single-mod PRP patch complete!');",
    "  AddMessage('[Mossy]   Source mod    : ' + sourceName);",
    "  AddMessage('[Mossy]   Patch file    : ' + patchFileName);",
    "  AddMessage('[Mossy]   CELLs copied  : ' + IntToStr(cellsCopied));",
    "  AddMessage('[Mossy]   CELLs PRP-fixed: ' + IntToStr(cellsFixed));",
    "  AddMessage('[Mossy] ======================================');",
    "  AddMessage('[Mossy] Next steps:');",
    "  AddMessage('[Mossy]   1. Save and exit FO4Edit.');",
    "  AddMessage('[Mossy]   2. In MO2, enable \"' + patchFileName + '\".');",
    "  AddMessage('[Mossy]   3. Load order: Masters -> PRP -> Your Mod -> ' + patchFileName);",
    "  AddMessage('');",
    '  Result := 0;',
    'end;',
    '',
    'end.',
  ].join('\n');
};
